const englishIndex = new Map(Object.entries(LOCALE).map(([key, value]) => [value.en, key]));

export function text(keyOrEnglish, lang = 'ar') {
  const key = LOCALE[keyOrEnglish] ? keyOrEnglish : englishIndex.get(keyOrEnglish);
  const value = key ? LOCALE[key] : null;
  return value?.[lang] || value?.en || keyOrEnglish;
}

export function format(key, values, lang = 'ar') {
  return text(key, lang).replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`);
}

